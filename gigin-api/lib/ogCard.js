function crc32(buf) {
  let crc = ~0;
  for (let i = 0; i < buf.length; i += 1) {
    crc ^= buf[i];
    for (let bit = 0; bit < 8; bit += 1) crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
  }
  return ~crc >>> 0;
}

function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length, 0);
  const name = Buffer.from(type);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([name, data])), 0);
  return Buffer.concat([length, name, data, crc]);
}

function blit(pixels, width, text, x, y, scale, color) {
  let cursor = x;
  const glyphs = [...String(text || "").toUpperCase()].map((ch) => FONT[ch] || FONT[" "]);
  for (const glyph of glyphs) {
    for (let row = 0; row < glyph.length; row += 1) {
      for (let col = 0; col < glyph[row].length; col += 1) {
        if (glyph[row][col] !== "1") continue;
        for (let sy = 0; sy < scale; sy += 1) {
          for (let sx = 0; sx < scale; sx += 1) {
            const px = cursor + col * scale + sx;
            const py = y + row * scale + sy;
            if (px < 0 || py < 0 || px >= width || py >= pixels.length / (width * 3)) continue;
            const offset = (py * width + px) * 3;
            pixels[offset] = color[0];
            pixels[offset + 1] = color[1];
            pixels[offset + 2] = color[2];
          }
        }
      }
    }
    cursor += (5 + 1) * scale;
  }
}

/** 1200×630 card: #111317, initials and the gigin. wordmark. */
export function ogCardPng(initials) {
  const width = 1200;
  const height = 630;
  const raw = Buffer.alloc((width * 3 + 1) * height);
  for (let y = 0; y < height; y += 1) {
    const row = y * (width * 3 + 1);
    raw[row] = 0;
    for (let x = 0; x < width; x += 1) {
      const offset = row + 1 + x * 3;
      raw[offset] = 0x11;
      raw[offset + 1] = 0x13;
      raw[offset + 2] = 0x17;
    }
  }
  const pixels = Buffer.alloc(width * height * 3, 0x11);
  for (let i = 0; i < pixels.length; i += 3) {
    pixels[i] = 0x11;
    pixels[i + 1] = 0x13;
    pixels[i + 2] = 0x17;
  }
  const mark = String(initials || "G").replace(/[^a-z0-9]/gi, "").slice(0, 3) || "G";
  blit(pixels, width, mark, 80, 220, 18, [255, 255, 255]);
  blit(pixels, width, "gigin.", 80, 460, 6, [255, 255, 255]);
  for (let y = 0; y < height; y += 1) {
    raw.set(pixels.subarray(y * width * 3, (y + 1) * width * 3), y * (width * 3 + 1) + 1);
  }
  const compressed = zlib.deflateSync(raw);
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 2;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", ihdr),
    chunk("IDAT", compressed),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}
